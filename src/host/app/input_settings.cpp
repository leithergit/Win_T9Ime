constexpr char kMarker[] = "# Generated by T9Ime settings";
constexpr char kStampFile[] = "t9ime.deployed";
const char* const kSchemas[] = {"t9", "rime_ice"};

std::string ReadText(const std::filesystem::path& p) {
  std::ifstream f(p, std::ios::binary);
  if (!f) return {};
  std::stringstream s;
  s << f.rdbuf();
  std::string t = s.str();
  t.erase(std::remove(t.begin(), t.end(), '\r'), t.end());
  return t;
}

bool WriteText(const std::filesystem::path& p, const std::string& text) {
  std::ofstream f(p, std::ios::binary | std::ios::trunc);
  f << text;
  return static_cast<bool>(f);
}

// The rules of `speller/algebra` in a schema file (comments and quotes as in
// the file; trailing " # comment" removed).
std::vector<std::string> SpellerAlgebra(const std::string& schema) {
  std::vector<std::string> rules;
  const size_t speller = schema.find("\nspeller:\n");
  if (speller == std::string::npos) return rules;
  const size_t algebra = schema.find("\n  algebra:\n", speller);
  if (algebra == std::string::npos) return rules;
  std::istringstream in(schema.substr(algebra + 12));
  std::string line;
  while (std::getline(in, line)) {
    if (line.empty()) continue;
    if (line.rfind("    ", 0) != 0) break;  // end of the list
    std::string item = line.substr(4);
    if (item.rfind("#", 0) == 0) continue;  // commented out
    if (item.rfind("- ", 0) != 0) break;
    item = item.substr(2);
    if (const size_t c = item.find(" #"); c != std::string::npos) item.resize(c);
    while (!item.empty() && item.back() == ' ') item.pop_back();
    rules.push_back(item);
  }
  return rules;
}

std::vector<std::string> FuzzyRules(const InputSettings& s) {
  std::vector<std::string> out;
  for (const FuzzyOption& o : FuzzyOptions()) {
    if (std::find(s.fuzzy.begin(), s.fuzzy.end(), o.id) == s.fuzzy.end()) continue;
    for (const char* r : o.rules) out.push_back(r);
  }
  return out;
}

// Size and write time of the shipped compiled data: changes with every upgrade.
std::string SharedIdentity(const std::filesystem::path& shared) {
  std::string id;
  for (const char* name : {"default.yaml", "t9.schema.yaml", "rime_ice.schema.yaml", "t9.prism.bin",
                           "rime_ice.table.bin"}) {
    std::error_code ec;
    const auto p = shared / "build" / name;
    const auto size = std::filesystem::file_size(p, ec);
    const auto time = std::filesystem::last_write_time(p, ec).time_since_epoch().count();
    id += std::string(name) + " " + std::to_string(ec ? 0 : size) + " " + std::to_string(ec ? 0 : time) + "\n";
  }
  return id;
}

std::string DeploymentStamp(const std::filesystem::path& shared, const std::filesystem::path& user) {
  std::string stamp = SharedIdentity(shared);
  for (const char* schema : kSchemas) stamp += ReadText(user / (std::string(schema) + ".custom.yaml"));
  return stamp;
}

bool IsGenerated(const std::filesystem::path& p) { return ReadText(p).rfind(kMarker, 0) == 0; }

