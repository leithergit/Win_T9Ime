const std::vector<FuzzyOption>& FuzzyOptions() {
  static const std::vector<FuzzyOption> options = {
      {"z", L"z = zh", {"derive/^zh/z/", "derive/^z([^h])/zh$1/"}},
      {"c", L"c = ch", {"derive/^ch/c/", "derive/^c([^h])/ch$1/"}},
      {"s", L"s = sh", {"derive/^sh/s/", "derive/^s([^h])/sh$1/"}},
      {"nl", L"n = l", {"derive/^n/l/", "derive/^l/n/"}},
      {"fh", L"f = h", {"derive/^f/h/", "derive/^h/f/"}},
      {"rl", L"r = l", {"derive/^r/l/", "derive/^l/r/"}},
      {"an", L"an = ang", {"derive/ang$/an/", "derive/an$/ang/"}},
      {"en", L"en = eng", {"derive/eng$/en/", "derive/en$/eng/"}},
      {"in", L"in = ing", {"derive/ing$/in/", "derive/in$/ing/"}},
      {"ian", L"ian = iang", {"derive/iang$/ian/", "derive/ian$/iang/"}},
      {"uan", L"uan = uang", {"derive/uang$/uan/", "derive/uan$/uang/"}},
  };
  return options;
}

InputSettings LoadInputSettings(const std::wstring& ini) {
  InputSettings s;
  if (ini.empty()) return s;
  s.traditional = GetPrivateProfileIntW(L"input", L"traditional", 0, ini.c_str()) != 0;
  s.page_size = std::clamp(static_cast<int>(GetPrivateProfileIntW(L"input", L"page_size", 5, ini.c_str())),
                           kMinPageSize, kMaxPageSize);
  wchar_t buf[256] = {};
  GetPrivateProfileStringW(L"input", L"fuzzy", L"", buf, 256, ini.c_str());
  const std::wstring list = std::wstring(L",") + buf + L",";
  for (const FuzzyOption& o : FuzzyOptions()) {
    const std::string id = o.id;
    if (list.find(L"," + std::wstring(id.begin(), id.end()) + L",") != std::wstring::npos) s.fuzzy.push_back(o.id);
  }
  return s;
}

void SaveInputSettings(const std::wstring& ini, const InputSettings& s) {
  if (ini.empty()) return;
  WritePrivateProfileStringW(L"input", L"traditional", s.traditional ? L"1" : L"0", ini.c_str());
  WritePrivateProfileStringW(L"input", L"page_size", std::to_wstring(s.page_size).c_str(), ini.c_str());
  std::wstring list;
  for (const std::string& id : s.fuzzy) list += (list.empty() ? L"" : L",") + std::wstring(id.begin(), id.end());
  WritePrivateProfileStringW(L"input", L"fuzzy", list.c_str(), ini.c_str());
}

std::string GenerateCustomization(const std::filesystem::path& shared, const std::string& schema,
                                  const InputSettings& s) {
  const std::vector<std::string> fuzzy = FuzzyRules(s);
  const bool page = schema == "rime_ice" && s.page_size != InputSettings{}.page_size;
  if (fuzzy.empty() && !page) return {};

  std::string base = ReadText(shared / (schema + ".custom.yaml"));
  if (base.find("\npatch:") == std::string::npos && base.rfind("patch:", 0) != 0) base += "patch:\n";
  while (!base.empty() && base.back() == '\n') base.pop_back();
  std::string out = std::string(kMarker) + " (shipped patch + settings); do not edit, it is regenerated.\n" + base +
                    "\n";
  if (!fuzzy.empty()) {
    std::vector<std::string> rules = SpellerAlgebra(ReadText(shared / (schema + ".schema.yaml")));
    // Fuzzy rules act on letters: before the nine-key digit mapping, or first.
    auto at = rules.begin();
    if (schema == "t9") {
      at = std::find_if(rules.begin(), rules.end(), [](const std::string& r) { return r.rfind("derive/[abc]/2/", 0) == 0; });
    }
    rules.insert(at, fuzzy.begin(), fuzzy.end());
    out += "  speller/algebra:\n";
    for (const std::string& r : rules) out += "    - " + r + "\n";
  }
  if (page) out += "  menu/page_size: " + std::to_string(s.page_size) + "\n";
  return out;
}

bool PrepareUserData(const std::filesystem::path& shared, const std::filesystem::path& user, const InputSettings& s) {
  std::error_code ec;
  std::filesystem::create_directories(user, ec);
  bool customized = false;
  for (const char* schema : kSchemas) {
    const auto file = user / (std::string(schema) + ".custom.yaml");
    const std::string text = GenerateCustomization(shared, schema, s);
    if (!text.empty()) {
      customized = true;
      if (ReadText(file) != text) WriteText(file, text);
    } else if (IsGenerated(file)) {
      std::filesystem::remove(file, ec);  // defaults again: the shipped patch applies
    }
  }
  const auto build = user / "build";
  const bool has_build = std::filesystem::exists(build, ec);
  if (!customized) {
    // Compiled data from earlier settings would hide the shipped data (also
    // after an upgrade): the pre-deployed data is used directly.
    if (has_build) std::filesystem::remove_all(build, ec);
    std::filesystem::remove(user / kStampFile, ec);
    return false;
  }
  return !has_build || ReadText(user / kStampFile) != DeploymentStamp(shared, user);
}

void MarkDeployed(const std::filesystem::path& shared, const std::filesystem::path& user) {
  WriteText(user / kStampFile, DeploymentStamp(shared, user));
}

